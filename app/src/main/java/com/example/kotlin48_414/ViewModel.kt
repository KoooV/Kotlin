    /**
     * Cold Flow — при каждом collect будет заново запущена генерация:
     * имитация загрузки (delay) и затем emit случайного факта.
     */
    fun getRandomFact(): Flow<String> = flow {
        val delayMs = (1500L..3000L).random()
        delay(delayMs)
        val fact = facts.random()
        emit(fact)
    }
